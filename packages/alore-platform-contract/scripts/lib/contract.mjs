import { cutUpstream } from './cut.mjs';
import { readJson, readText, readYaml, sha256, toYaml } from './io.mjs';
import { applyOverlay } from './overlay.mjs';
import { FILES } from './paths.mjs';
import { addStandardProblemResponses } from './problem-responses.mjs';

export const PINNED_HEADER = `# Generated by scripts/cut.mjs from openapi/upstream/openapi.yaml. Do not edit by hand.
# Source of the cut: routes/served.yaml and the upstream-backed rows of routes/planned.yaml.
`;
export const OPENAPI_HEADER = `# Generated by scripts/generate.mjs from the pinned cut, x-alore overlay and standard problem responses.
# Never edit by hand: change the overlay, the schemas or the routes, then run generate.
`;

export function loadRoutes() {
  return {
    served: readYaml(FILES.served).routes,
    planned: readYaml(FILES.planned).routes,
  };
}

/**
 * Routes the cut keeps from upstream. The cut keeps an operation whenever the pinned
 * spec has one, whatever the route table's upstream_openai flag says: upstream wins.
 */
export function upstreamRoutes({ served, planned }) {
  return [...served, ...planned];
}

export function loadPin() {
  return readJson(FILES.pin);
}

export function verifyPin(pin) {
  const actual = sha256(readText(FILES.upstream));
  if (actual !== pin.sha256) {
    throw new Error(
      `openapi/upstream/openapi.yaml sha256 ${actual} does not match PIN.json ${pin.sha256}`,
    );
  }
}

/** Build every generated artefact in memory. */
export function buildContract({ upstream, routes, pin, overlay, version }) {
  const { doc: pinned, missing } = cutUpstream(upstream, upstreamRoutes(routes), pin);
  // Served routes with no upstream equivalent are defined by the overlay.
  const merged = applyOverlay(pinned, overlay);
  addStandardProblemResponses(merged);
  merged.info.version = version;
  merged['x-alore-contract'] = { version };
  return { pinned, merged, missing };
}

export const render = {
  pinned: (doc) => toYaml(doc, PINNED_HEADER),
  openapi: (doc) => toYaml(doc, OPENAPI_HEADER),
};
